import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { PGlite } from '@electric-sql/pglite';
import { importOperations } from '../scripts/import-operations.js';
import { executeOperation } from '../src/modules/operations/service.js';
import { createDomain } from '../src/modules/operations/runtime.js';
import { createApp } from '../src/app.js';
import { readConfig } from '../src/config.js';
import { digest } from '../src/shared/security.js';

test('original dataset imports atomically, preserves auth, and shared workflows survive fresh server runtimes', async () => {
  const engine = new PGlite();
  let server;
  const db = { query: (sql, params) => engine.query(sql, params), connect: async () => ({ query: (sql, params) => engine.query(sql, params), release() {} }) };
  try {
    for (const file of ['001_foundation.sql', '002_operations.sql', '003_workflow_records.sql','004_equipment_allocations.sql','005_login_access_controls.sql','007_staff_number_counters.sql']) await engine.exec(await readFile(new URL(`../migrations/${file}`, import.meta.url), 'utf8'));
    const supervisor = { id: randomUUID(), email: 'supervisor@example.test', name: 'Nimal Perera', role: 'SUPERVISOR', title: 'Supervisor' };
    const employee = { id: randomUUID(), email: 'employee@example.test', name: 'Kasun Silva', role: 'EMPLOYEE', title: 'Employee' };
    const other = { ...employee, id: randomUUID(), email: 'other@example.test' };
    for (const user of [supervisor, employee, other]) await db.query('INSERT INTO users(id,email,name,role,password_hash) VALUES($1,$2,$3,$4,$5)', [user.id, user.email, user.name, user.role, 'preserved-password-hash']);
    await db.query("INSERT INTO user_permissions(user_id,permission) VALUES($1,'audit.read')", [supervisor.id]);
    await db.query("INSERT INTO sessions(token_hash,user_id,csrf_token,expires_at) VALUES('kept-session',$1,'kept-csrf',now()+interval '1 day')", [employee.id]);
    const before = await db.query('SELECT * FROM users ORDER BY id');
    const result = await importOperations(db, { backup: false, nodeEnv: 'test' });
    assert.equal(result.imported.employees, 392);
    assert.equal(result.imported.offDays, 2417);
    assert.deepEqual(await db.query('SELECT * FROM users ORDER BY id'), before);
    assert.equal((await db.query('SELECT * FROM sessions')).rows.length, 1);
    assert.equal((await db.query('SELECT * FROM user_permissions')).rows.length, 1);
    await assert.rejects(importOperations(db, { backup: false, nodeEnv: 'test' }), /already imported/);
    const auth = { user: supervisor, permissions: ['audit.read'] };
    const own = { user: employee, permissions: [] };
    const operation = (actor, method, args = [], group = 'workflows') => executeOperation(db, actor, group, method, args);
    const dashboard = await operation(auth, 'getDashboard', [{}]);
    assert.equal(dashboard.kpis.permanentEmployees, 392);
    const work = await operation(own, 'getMyWork');
    assert.equal(work.person.id, employee.id);
    const roster = await operation(own, 'getRoster', [{ month: '2026-09' }]);
    assert.equal(roster.rows.length, 1);
    assert.equal(roster.rows[0].employeeId, employee.id);
    await assert.rejects(operation(own, 'getEmployee', [other.id]), error => error.status === 403);
    await assert.rejects(operation(own, 'listEmployees', [{}]), error => error.status === 403);
    await assert.rejects(operation(auth, 'constructor'), error => error.status === 404);
    await assert.rejects(operation(auth, 'setMockConfig', [{}]), error => error.status === 404);
    await assert.rejects(operation(auth, 'decideWarning', ['missing', 'APPROVE']), error => error.status === 403);
    const category = await operation(auth, 'createPlatformCategory', [{ code: 'NEWTEST', name: 'New category', description: 'Persisted category' }]);
    assert.ok(category);
    const fresh = await operation(auth, 'listCategories', []);
    assert.ok(fresh.some(row => row.code === 'NEWTEST'));
    assert.equal((await db.query("SELECT count(*)::int AS n FROM ops_categories WHERE data->>'code'='NEWTEST'")).rows[0].n, 1);
    const audit = await operation(auth, 'listAudit', [{}]);
    assert.ok(audit.items.length > 0);
    const snapshot = await operation(own, 'snapshot', [], 'breaks');
    assert.equal(snapshot.available, true);
    const profile = await operation(own, 'getProfile', [employee.id, '2026-09-01', '2026-09-30']);
    assert.equal(profile.record.id, employee.id);
    // Every legacy callable is explicitly exposed except demo login/configuration controls.
    assert.ok(Object.keys((await createDomain()).methods).length >= 110);
    await db.query("INSERT INTO user_permissions(user_id,permission) VALUES($1,'accounts.manage')", [supervisor.id]);
    await db.query("INSERT INTO sessions(token_hash,user_id,csrf_token,expires_at) VALUES($1,$2,'mapping-csrf',now()+interval '1 day')", [digest('mapping-test-token'), supervisor.id]);
    server = createApp(db, readConfig({ NODE_ENV:'test', DATABASE_URL:'postgresql://unused', FRONTEND_ORIGIN:'http://localhost:5173' })).listen(0,'127.0.0.1');
    await new Promise(resolve => server.once('listening', resolve));
    const endpoint = `http://127.0.0.1:${server.address().port}/api/v1/operations/links`;
    const headers = { Cookie:'pcd_session=mapping-test-token', Origin:'http://localhost:5173', 'Content-Type':'application/json', 'X-CSRF-Token':'mapping-csrf' };
    assert.equal((await fetch(endpoint, { headers })).status, 200);
    const taken = (await db.query('SELECT worker_id FROM operational_accounts WHERE user_id=$1', [other.id])).rows[0].worker_id;
    const conflict = await fetch(`${endpoint}/${employee.id}`, { method:'PUT', headers, body:JSON.stringify({workerId:taken}) });
    assert.equal(conflict.status, 409);
    const available = (await db.query("SELECT e.id FROM ops_employees e WHERE NOT EXISTS(SELECT 1 FROM operational_accounts a WHERE a.worker_id=e.id) LIMIT 1")).rows[0].id;
    const changed = await fetch(`${endpoint}/${employee.id}`, { method:'PUT', headers, body:JSON.stringify({workerId:available}) });
    assert.equal(changed.status, 204);
    assert.equal((await db.query('SELECT count(*)::int AS n FROM sessions WHERE user_id=$1', [employee.id])).rows[0].n, 0);
    const oldLink = (await db.query('SELECT worker_id FROM operational_accounts WHERE user_id=$1', [employee.id])).rows[0].worker_id;
    assert.equal(oldLink, available);
  } finally { if (server) await new Promise(resolve => server.close(resolve)); await engine.close(); }
});
